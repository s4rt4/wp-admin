<h2>Revision Diff Viewer</h2>

<p>Revision Diff Viewer memungkinkan Anda membandingkan dua versi postingan secara berdampingan, dengan highlight apa yang ditambahkan dan dihapus antar revisi.</p>

<h3>Cara Menggunakan</h3>
<ol>
    <li>Buka postingan untuk diedit (<strong>Posts &rarr; Edit</strong>).</li>
    <li>Di sidebar, buka metabox <strong>Revisions</strong>.</li>
    <li>Setiap entri revisi memiliki tombol <strong>Compare</strong> (<i class="fa-solid fa-code-compare"></i>) — klik untuk membandingkan revisi tersebut dengan versi sebelumnya.</li>
    <li>Modal terbuka menampilkan kedua versi berdampingan:
        <ul>
            <li><span style="color:#991b1b;background:#fecaca;padding:1px 4px;">Baris merah</span> = teks yang dihapus (versi lama).</li>
            <li><span style="color:#166534;background:#bbf7d0;padding:1px 4px;">Baris hijau</span> = teks yang ditambahkan (versi baru).</li>
            <li>Baris yang tidak berubah tampil normal di kedua kolom.</li>
        </ul>
    </li>
</ol>

<h3>Memulihkan Revisi</h3>
<p>Klik <strong>Restore</strong> di samping revisi mana pun untuk mengganti konten editor saat ini dengan konten revisi tersebut. Jangan lupa simpan postingan setelah memulihkan.</p>

<h3>Catatan</h3>
<ul>
    <li>Revisi baru otomatis disimpan setiap kali Anda memperbarui postingan.</li>
    <li>Hanya 20 revisi terakhir per postingan yang disimpan.</li>
    <li>Diff viewer membandingkan konten teks biasa (tag HTML dihilangkan untuk keterbacaan).</li>
</ul>
