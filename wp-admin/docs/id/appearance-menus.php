<h1>Pengaturan Menu Navigasi</h1>
<p class="docs-lead">Menu <strong>Tampilan &rarr; Menu</strong> memungkinkan Anda membuat dan mengatur menu navigasi yang tampil di situs, seperti menu header, footer, atau sidebar.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('menus-pages.png'); ?>" alt="Pengaturan Menu" onerror="this.style.display='none'">
    <p class="docs-caption">Halaman pengaturan menu navigasi situs.</p>
</div>

<hr class="docs-divider">

<h2>Cara Membuat Menu Baru</h2>
<ol class="docs-steps">
    <li>
        <strong>Buka Pengaturan Menu</strong>
        <p>Klik <strong>Tampilan &rarr; Menu</strong> di sidebar admin.</p>
    </li>
    <li>
        <strong>Beri Nama Menu</strong>
        <p>Di bagian atas, isi kolom <em>Nama Menu</em> dengan nama yang mudah dikenali (misalnya: "Menu Utama", "Menu Footer").</p>
    </li>
    <li>
        <strong>Tambahkan Item Menu</strong>
        <p>Di panel kiri, pilih item yang ingin ditambahkan ke menu:</p>
        <ul class="docs-list">
            <li><strong>Halaman</strong> — Pilih dari daftar halaman yang ada.</li>
            <li><strong>Postingan</strong> — Pilih artikel dari daftar postingan.</li>
            <li><strong>Tautan Kustom</strong> — Masukkan URL dan nama tautan secara manual.</li>
            <li><strong>Kategori</strong> — Tambahkan link ke halaman arsip kategori.</li>
        </ul>
        <p>Klik <strong>Tambahkan ke Menu</strong> setelah memilih.</p>
    </li>
    <li>
        <strong>Atur Urutan &amp; Hierarki</strong>
        <p>Seret dan lepas item menu di panel kanan untuk mengubah urutannya. Geser ke kanan untuk membuat sub-menu (dropdown).</p>
    </li>
    <li>
        <strong>Tetapkan Lokasi Menu</strong>
        <p>Di bagian <em>Pengaturan Menu</em>, centang lokasi tempat menu ini akan ditampilkan (Header, Footer, dsb.).</p>
    </li>
    <li>
        <strong>Simpan Menu</strong>
        <p>Klik tombol <strong>Simpan Menu</strong>.</p>
    </li>
</ol>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tips:</strong> Gunakan <em>Tautan Kustom</em> untuk menambahkan tautan ke situs eksternal atau halaman yang belum dibuat di admin, seperti tautan ke profil media sosial.
    </div>
</div>
