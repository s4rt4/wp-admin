<h1>Postingan Terpublikasi</h1>
<p class="docs-lead">Halaman <strong>Postingan Terpublikasi</strong> menampilkan semua artikel yang sudah tayang dan dapat diakses oleh pengunjung situs.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('published-post.png'); ?>" alt="Postingan Terpublikasi" onerror="this.style.display='none'">
    <p class="docs-caption">Daftar postingan yang sudah dipublikasikan.</p>
</div>

<hr class="docs-divider">

<h2>Cara Mengelola Postingan Terpublikasi</h2>
<ol class="docs-steps">
    <li>
        <strong>Filter Postingan Terpublikasi</strong>
        <p>Buka <strong>Postingan &rarr; Semua Postingan</strong>, lalu klik tab <strong>Dipublikasikan</strong> untuk melihat hanya postingan yang sudah tayang.</p>
    </li>
    <li>
        <strong>Edit Postingan yang Sudah Tayang</strong>
        <p>Klik judul postingan untuk membuka editor dan melakukan perubahan. Klik <strong>Perbarui</strong> untuk menyimpan perubahan. Postingan tetap tayang selama proses pengeditan.</p>
    </li>
    <li>
        <strong>Kembalikan ke Draf</strong>
        <p>Buka editor postingan, ubah status dari <em>Dipublikasikan</em> menjadi <em>Draf</em>, lalu klik <strong>Perbarui</strong>. Postingan akan disembunyikan dari publik.</p>
    </li>
    <li>
        <strong>Hapus Postingan</strong>
        <p>Arahkan kursor ke judul di daftar dan klik <em>Hapus</em>. Tindakan ini bersifat permanen.</p>
    </li>
</ol>

<div class="docs-warning">
    <span class="dashicons dashicons-warning"></span>
    <div>
        <strong>Perhatian:</strong> Perubahan yang dilakukan pada postingan yang sudah tayang akan langsung terlihat oleh pengunjung situs setelah disimpan. Pastikan konten sudah diperiksa sebelum memperbaru.
    </div>
</div>

<hr class="docs-divider">

<h2>Tips Manajemen Konten Terpublikasi</h2>
<ul class="docs-list">
    <li>Lakukan review berkala terhadap postingan lama untuk memastikan informasinya masih relevan dan akurat.</li>
    <li>Perbarui tanggal postingan jika Anda melakukan pembaruan konten besar agar terlihat lebih segar oleh mesin pencari.</li>
    <li>Gunakan fitur duplikasi postingan jika ingin membuat postingan serupa tanpa memulai dari awal.</li>
</ul>
