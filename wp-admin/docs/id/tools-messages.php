<h2>Pesan Internal</h2>
<p>Kirim dan terima pesan antar pengguna admin langsung di dalam CMS.</p>

<h3>Fitur</h3>
<ul>
    <li><strong>Inbox / Sent</strong> — Beralih antara pesan masuk dan pesan terkirim.</li>
    <li><strong>Compose</strong> — Klik bagian compose untuk membuka form. Pilih user, tambah subjek, dan tulis pesan.</li>
    <li><strong>Thread Balasan</strong> — Klik pesan untuk melihatnya beserta semua balasan. Balas langsung dari halaman view.</li>
    <li><strong>Badge Belum Dibaca</strong> — Jumlah belum dibaca ditampilkan di tab Inbox.</li>
    <li><strong>Notifikasi</strong> — Penerima otomatis mendapat notifikasi in-app saat ada pesan baru.</li>
</ul>
