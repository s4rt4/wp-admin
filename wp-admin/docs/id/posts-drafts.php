<h1>Draf Postingan</h1>
<p class="docs-lead">Draf adalah postingan yang belum dipublikasikan. Anda bisa menyimpan konten yang masih dalam proses penulisan sebagai draf dan melanjutkannya kapan saja.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('draft-post.png'); ?>" alt="Draf Postingan" onerror="this.style.display='none'">
    <p class="docs-caption">Daftar postingan yang tersimpan sebagai draf.</p>
</div>

<hr class="docs-divider">

<h2>Cara Mengelola Draf</h2>
<ol class="docs-steps">
    <li>
        <strong>Lihat Semua Draf</strong>
        <p>Buka <strong>Postingan &rarr; Semua Postingan</strong>, lalu klik tab <strong>Draf</strong> di bagian atas tabel.</p>
    </li>
    <li>
        <strong>Lanjutkan Penulisan Draf</strong>
        <p>Klik judul draf yang ingin dilanjutkan untuk membuka editor. Lakukan perubahan dan klik <strong>Simpan Draf</strong> untuk menyimpan, atau <strong>Publikasikan</strong> jika sudah siap.</p>
    </li>
    <li>
        <strong>Jadwalkan Publikasi</strong>
        <p>Di panel <em>Status &amp; Visibilitas</em>, klik <em>Segera</em> pada bagian Publikasikan, lalu atur tanggal dan waktu publikasi yang diinginkan.</p>
    </li>
    <li>
        <strong>Hapus Draf</strong>
        <p>Arahkan kursor ke judul draf di daftar dan klik <em>Hapus</em> untuk menghapus draf secara permanen.</p>
    </li>
</ol>

<hr class="docs-divider">

<h2>Tips Pengelolaan Draf</h2>
<ul class="docs-list">
    <li>Buat draf judul terlebih dahulu meskipun kontennya belum lengkap &mdash; ini memudahkan perencanaan konten ke depan.</li>
    <li>Gunakan fitur penjadwalan untuk memastikan postingan dipublikasikan di waktu yang optimal (misalnya jam sibuk trafik situs).</li>
    <li>Tambahkan catatan di dalam draf tentang apa yang masih perlu dilengkapi sebelum dipublikasikan.</li>
</ul>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tips:</strong> Draf tidak terlihat oleh pengunjung situs. Anda bisa menggunakannya untuk menyiapkan konten jauh-jauh hari sebelum tanggal publikasi.
    </div>
</div>
