<h2>Trash / Tempat Sampah</h2>

<p>Saat Anda menghapus postingan atau halaman, item tersebut tidak langsung dihapus permanen. Sebaliknya, item dipindahkan ke <strong>Trash (Tempat Sampah)</strong> — area aman di mana item bisa dipulihkan atau dihapus permanen.</p>

<h3>Cara Kerja</h3>
<ul>
    <li><strong>Trash:</strong> Klik "Trash" pada baris aksi postingan atau halaman untuk menghapus sementara. Status item berubah menjadi <code>trash</code> dan menghilang dari daftar utama.</li>
    <li><strong>Tab Trash:</strong> Tab filter "Trash" berwarna merah muncul di daftar Posts dan Pages ketika ada item yang di-trash. Klik untuk melihat semua konten yang di-trash.</li>
    <li><strong>Restore (Pulihkan):</strong> Di tampilan Trash, klik "Restore" untuk mengembalikan item ke status <strong>Draft</strong>.</li>
    <li><strong>Delete Permanently (Hapus Permanen):</strong> Klik "Delete Permanently" untuk menghapus item secara permanen beserta semua data terkait (kategori, tag, custom fields).</li>
    <li><strong>Empty Trash (Kosongkan Trash):</strong> Klik tombol "Empty Trash" di bagian atas untuk menghapus semua item trash sekaligus.</li>
</ul>

<h3>Catatan</h3>
<ul>
    <li>Postingan yang di-trash tidak dihitung di tab "All" dan tidak akan tampil di frontend.</li>
    <li>Tab Trash hanya muncul jika ada minimal satu item di trash.</li>
    <li>Fitur Trash tersedia untuk Posts maupun Pages.</li>
</ul>
