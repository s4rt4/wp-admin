<h2>Bulk SEO Editor</h2>
<p>Bulk SEO Editor memungkinkan Anda mengedit metadata SEO semua post sekaligus dalam satu tampilan spreadsheet, tanpa perlu membuka setiap post satu per satu.</p>

<h3>Cara Mengakses</h3>
<p>Buka <strong>Posts → Bulk SEO Editor</strong> di sidebar admin.</p>

<h3>Field yang Bisa Diedit</h3>
<ul>
    <li><strong>SEO Title</strong> — Judul yang ditampilkan di hasil pencarian. Panjang optimal: 30–60 karakter. Jumlah karakter ditampilkan dalam tanda kurung dengan indikator warna.</li>
    <li><strong>Meta Description</strong> — Cuplikan yang ditampilkan di bawah judul di hasil pencarian. Panjang optimal: 120–160 karakter.</li>
    <li><strong>Slug</strong> — Identifier URL-friendly untuk post.</li>
    <li><strong>Focus Keyword</strong> — Kata kunci utama yang ingin Anda targetkan.</li>
</ul>

<h3>Cara Mengedit</h3>
<ol>
    <li>Klik pada sel yang ingin diedit (SEO Title, Meta Description, Slug, atau Focus Keyword).</li>
    <li>Ketik perubahan Anda.</li>
    <li>Tekan <kbd>Enter</kbd> atau klik di luar sel untuk menyimpan.</li>
    <li>Indikator hijau "Saved" akan muncul sebentar sebagai konfirmasi.</li>
</ol>

<h3>Indikator Warna</h3>
<ul>
    <li><span style="color:#065f46;font-weight:600;">Hijau</span> — Panjang dalam rentang optimal.</li>
    <li><span style="color:#856404;font-weight:600;">Kuning</span> — Ada konten tapi di luar rentang optimal.</li>
    <li><span style="color:#d63638;font-weight:600;">Merah</span> — Kosong atau perlu perhatian.</li>
</ul>

<h3>Cari & Urutkan</h3>
<p>Gunakan kotak pencarian untuk memfilter post berdasarkan judul atau slug. Klik header kolom untuk mengurutkan grid.</p>
