<h2>Data Explorer</h2>
<p>Data Explorer memungkinkan administrator menjelajahi tabel database mana pun langsung dari panel admin dalam grid interaktif yang read-only.</p>

<h3>Cara Mengakses</h3>
<p>Buka <strong>Tools → Data Explorer</strong> di sidebar admin. Memerlukan kapabilitas <em>manage_options</em>.</p>

<h3>Fitur</h3>
<ul>
    <li><strong>Pemilih Tabel</strong> — Dropdown berisi semua tabel database. Pilih salah satu untuk memuat datanya.</li>
    <li><strong>Deteksi Kolom Otomatis</strong> — Header dan lebar kolom ditentukan otomatis dari skema tabel.</li>
    <li><strong>Pengurutan</strong> — Klik header kolom untuk mengurutkan naik/turun.</li>
    <li><strong>Paginasi</strong> — 50 baris per halaman dengan paginasi client-side.</li>
    <li><strong>Ekspor CSV</strong> — Unduh data tabel sebagai file CSV.</li>
    <li><strong>Info Kolom</strong> — Menampilkan nama kolom dan tipe data di bawah toolbar.</li>
</ul>

<h3>Batasan</h3>
<ul>
    <li>Read-only — tidak bisa mengedit atau menghapus dari halaman ini.</li>
    <li>Maksimum 500 baris ditampilkan per tabel.</li>
    <li>Kolom TEXT/BLOB yang besar mungkin terpotong di tampilan grid.</li>
</ul>
