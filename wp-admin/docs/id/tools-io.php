<h1>Import &amp; Export Konten</h1>
<p class="docs-lead">Fitur <strong>Import/Export</strong> memungkinkan Anda memindahkan konten (postingan, halaman, media) antar situs atau membuat cadangan konten dalam format yang dapat dibaca ulang.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('import-export-content.png'); ?>" alt="Import Export Konten" onerror="this.style.display='none'">
    <p class="docs-caption">Panel import dan export konten situs.</p>
</div>

<hr class="docs-divider">

<h2>Cara Export Konten</h2>
<ol class="docs-steps">
    <li><strong>Buka Halaman Export</strong><p>Klik <strong>Peralatan &rarr; Import/Export</strong> dan pilih tab <strong>Export</strong>.</p></li>
    <li><strong>Pilih Jenis Konten</strong><p>Pilih apa yang ingin diekspor: Semua Konten, hanya Postingan, hanya Halaman, atau hanya Media.</p></li>
    <li><strong>Klik Export</strong><p>Klik tombol <strong>Export</strong>. File XML akan diunduh ke komputer Anda.</p></li>
</ol>

<hr class="docs-divider">

<h2>Cara Import Konten</h2>
<ol class="docs-steps">
    <li><strong>Pilih Tab Import</strong><p>Klik tab <strong>Import</strong> di halaman yang sama.</p></li>
    <li><strong>Upload File</strong><p>Klik <em>Pilih File</em> dan unggah file XML yang sebelumnya diekspor.</p></li>
    <li><strong>Petakan Penulis</strong><p>Petakan penulis dari file lama ke akun pengguna yang ada di situs ini.</p></li>
    <li><strong>Klik Import</strong><p>Klik tombol <strong>Jalankan Importir</strong> untuk memulai proses impor konten.</p></li>
</ol>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tips:</strong> Gunakan fitur Export secara berkala sebagai backup konten. Format XML dapat dibaca oleh berbagai platform CMS lain, sehingga konten Anda tidak terkunci di satu platform saja.
    </div>
</div>
