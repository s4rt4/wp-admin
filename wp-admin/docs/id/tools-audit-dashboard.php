<h2>Audit Dashboard</h2>
<p>Audit Dashboard memberikan ringkasan visual semua aktivitas admin dengan chart dan grid log interaktif.</p>

<h3>Cara Mengakses</h3>
<p>Buka <strong>Tools → Audit Dashboard</strong> di sidebar admin. Untuk log lengkap dengan filter, klik "View Full Log" untuk menuju halaman Audit Log.</p>

<h3>Fitur</h3>
<ul>
    <li><strong>Kartu Statistik</strong> — Total event (30 hari), event hari ini, dan jumlah user aktif.</li>
    <li><strong>Timeline Aktivitas</strong> — Area chart menampilkan jumlah event harian selama 30 hari terakhir.</li>
    <li><strong>Top Actions</strong> — Bar chart horizontal dari tipe aksi paling umum (login, post_create, dll.).</li>
    <li><strong>Top Users</strong> — Bar chart horizontal dari user paling aktif berdasarkan jumlah event.</li>
    <li><strong>Grid Aktivitas Terbaru</strong> — Tabel tui-grid interaktif dengan 200 entri log terbaru. Badge aksi berwarna, kolom bisa diurutkan, dan paginasi.</li>
</ul>
