<h1>Kustomisasi Tampilan</h1>
<p class="docs-lead">Menu <strong>Tampilan &rarr; Kustomisasi</strong> memungkinkan Anda mengubah tampilan visual situs seperti warna, font, header, footer, dan elemen desain lainnya secara langsung melalui panel admin.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('customize.png'); ?>" alt="Halaman Kustomisasi Tampilan" onerror="this.style.display='none'">
    <p class="docs-caption">Panel kustomisasi tampilan situs.</p>
</div>

<hr class="docs-divider">

<h2>Cara Mengkustomisasi Tampilan</h2>
<ol class="docs-steps">
    <li>
        <strong>Buka Panel Kustomisasi</strong>
        <p>Klik menu <strong>Tampilan &rarr; Kustomisasi</strong> di sidebar admin.</p>
    </li>
    <li>
        <strong>Pilih Bagian yang Ingin Diubah</strong>
        <p>Di panel kiri, Anda akan melihat berbagai opsi kustomisasi. Klik salah satu untuk membuka pengaturannya:</p>
        <ul class="docs-list">
            <li><strong>Identitas Situs</strong> — Ubah nama situs, tagline, dan favicon.</li>
            <li><strong>Warna</strong> — Sesuaikan skema warna utama situs.</li>
            <li><strong>Header</strong> — Kustomisasi tampilan bagian atas halaman.</li>
            <li><strong>Footer</strong> — Atur konten dan tampilan bagian bawah halaman.</li>
            <li><strong>Typography</strong> — Pilih font dan ukuran teks.</li>
        </ul>
    </li>
    <li>
        <strong>Lihat Preview Langsung</strong>
        <p>Setiap perubahan yang Anda buat akan langsung terlihat di area preview di sebelah kanan panel.</p>
    </li>
    <li>
        <strong>Simpan Perubahan</strong>
        <p>Klik tombol <strong>Publikasikan</strong> untuk menerapkan semua perubahan ke situs secara langsung.</p>
    </li>
</ol>

<hr class="docs-divider">

