<h1>Perpustakaan Media</h1>
<p class="docs-lead"><strong>Perpustakaan Media</strong> adalah tempat semua file yang diunggah ke situs Anda tersimpan &mdash; mulai dari gambar, video, hingga dokumen PDF. Anda bisa mengelola seluruh aset media dari halaman ini.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('media-library.png'); ?>" alt="Perpustakaan Media" onerror="this.style.display='none'">
    <p class="docs-caption">Tampilan Perpustakaan Media dengan grid file.</p>
</div>

<hr class="docs-divider">

<h2>Cara Menggunakan Perpustakaan Media</h2>
<ol class="docs-steps">
    <li>
        <strong>Buka Perpustakaan Media</strong>
        <p>Klik menu <strong>Media &rarr; Perpustakaan</strong> di sidebar.</p>
    </li>
    <li>
        <strong>Cari File</strong>
        <p>Gunakan kotak pencarian di bagian atas atau filter berdasarkan tipe file (Gambar, Video, Audio, Dokumen) untuk menemukan file yang diinginkan.</p>
    </li>
    <li>
        <strong>Lihat Detail File</strong>
        <p>Klik salah satu file untuk membuka panel detail di sebelah kanan, yang menampilkan informasi seperti nama file, tipe, ukuran, dimensi, dan URL file.</p>
    </li>
    <li>
        <strong>Edit Informasi File</strong>
        <p>Di panel detail, Anda dapat mengedit <em>Judul</em>, <em>Teks Alternatif (Alt Text)</em>, <em>Caption</em>, dan <em>Deskripsi</em> file.</p>
    </li>
    <li>
        <strong>Salin URL File</strong>
        <p>Di panel detail, klik tombol <em>Salin URL</em> untuk mendapatkan tautan langsung ke file tersebut.</p>
    </li>
    <li>
        <strong>Hapus File</strong>
        <p>Di panel detail, klik <em>Hapus Permanen</em>. File yang sudah dihapus tidak dapat dipulihkan.</p>
    </li>
</ol>

<hr class="docs-divider">

<h2>Tips Pengelolaan Media</h2>
<ul class="docs-list">
    <li>Selalu isi <strong>Alt Text</strong> pada setiap gambar untuk meningkatkan aksesibilitas dan SEO.</li>
    <li>Kompres gambar sebelum mengunggah untuk menghemat ruang penyimpanan dan mempercepat loading halaman.</li>
    <li>Gunakan nama file yang deskriptif (misal: <code>logo-perusahaan.png</code>) daripada nama acak (misal: <code>IMG_001.png</code>).</li>
</ul>

<div class="docs-warning">
    <span class="dashicons dashicons-warning"></span>
    <div>
        <strong>Perhatian:</strong> Menghapus file dari perpustakaan media tidak akan otomatis menghapus referensinya dari postingan atau halaman. Tautan gambar yang dihapus akan menjadi rusak (broken).
    </div>
</div>
