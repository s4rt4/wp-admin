<h2>Media Editor</h2>
<p>Edit gambar langsung dari Media Library tanpa perlu download dan upload ulang. Editor bawaan mendukung crop, resize, rotate, dan flip.</p>

<h3>Cara Membuka</h3>
<ol>
    <li>Buka <strong>Media</strong> dan klik gambar mana pun.</li>
    <li>Di panel detail, klik tombol <strong>Edit Image</strong>.</li>
    <li>Modal editor gambar terbuka dengan workspace canvas gelap.</li>
</ol>

<h3>Tools</h3>
<ul>
    <li><strong>Rotate Left / Right:</strong> Putar gambar 90 derajat.</li>
    <li><strong>Flip Horizontal / Vertical:</strong> Cerminkan gambar secara horizontal atau vertikal.</li>
    <li><strong>Resize:</strong> Masukkan lebar (W) atau tinggi (H) baru. Kunci rasio aspek (ikon gembok) menjaga proporsi — klik untuk membuka kunci.</li>
    <li><strong>Crop:</strong> Klik tombol Crop, lalu drag area seleksi di canvas. Klik Crop lagi untuk menerapkan — gambar dipotong sesuai seleksi.</li>
    <li><strong>Reset:</strong> Kembalikan semua perubahan ke gambar asli.</li>
</ul>

<h3>Menyimpan</h3>
<p>Klik <strong>Save</strong> untuk menimpa file asli dengan hasil edit. Ukuran file di database media diperbarui otomatis. Tindakan ini tidak bisa dibatalkan — pertimbangkan untuk download backup terlebih dahulu jika diperlukan.</p>
