<h1>Postingan Unggulan</h1>
<p class="docs-lead">Fitur <strong>Postingan Unggulan</strong> memungkinkan Anda menandai postingan tertentu agar tampil di posisi atau area yang lebih menonjol di halaman situs, seperti slider, banner, atau bagian hero halaman depan.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('featured-posts.png'); ?>" alt="Halaman Postingan Unggulan" onerror="this.style.display='none'">
    <p class="docs-caption">Tampilan daftar postingan yang ditandai sebagai unggulan.</p>
</div>

<hr class="docs-divider">

<h2>Cara Mengelola Postingan Unggulan</h2>
<ol class="docs-steps">
    <li>
        <strong>Filter Postingan Unggulan</strong>
        <p>Buka <strong>Postingan &rarr; Semua Postingan</strong>, lalu klik tab <strong>Unggulan</strong> di bagian atas tabel untuk melihat hanya postingan yang sudah ditandai.</p>
    </li>
    <li>
        <strong>Tandai Postingan sebagai Unggulan</strong>
        <p>Buka editor postingan yang ingin Anda jadikan unggulan. Di panel samping kanan, aktifkan opsi <em>Tandai sebagai Unggulan</em> (toggle atau checkbox).</p>
    </li>
    <li>
        <strong>Hapus Status Unggulan</strong>
        <p>Buka kembali editor postingan, lalu nonaktifkan opsi <em>Tandai sebagai Unggulan</em> yang sebelumnya diaktifkan.</p>
    </li>
</ol>

<hr class="docs-divider">

<h2>Cara Kerja Postingan Unggulan</h2>
<p>Postingan yang ditandai sebagai unggulan akan:</p>
<ul class="docs-list">
    <li>Muncul di bagian <strong>Featured Posts</strong> atau slider di halaman depan (tergantung konfigurasi tema).</li>
    <li>Ditampilkan dengan label khusus <em>"Unggulan"</em> di daftar postingan admin.</li>
    <li>Bisa difilter dan dikelola khusus dari tab Unggulan di halaman Semua Postingan.</li>
</ul>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tips:</strong> Pilih postingan unggulan yang memiliki gambar berkualitas tinggi dan judul yang menarik, karena postingan ini biasanya tampil paling menonjol di halaman depan situs.
    </div>
</div>
