<h1>Tambah Pengguna Baru</h1>
<p class="docs-lead">Halaman <strong>Pengguna &rarr; Tambah Baru</strong> memungkinkan administrator membuat akun pengguna baru dengan peran yang ditentukan.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('add-new-user.png'); ?>" alt="Tambah Pengguna Baru" onerror="this.style.display='none'">
    <p class="docs-caption">Form tambah pengguna baru.</p>
</div>

<hr class="docs-divider">

<h2>Cara Menambah Pengguna Baru</h2>
<ol class="docs-steps">
    <li><strong>Buka Halaman Tambah Pengguna</strong><p>Klik <strong>Pengguna &rarr; Tambah Baru</strong> di sidebar.</p></li>
    <li><strong>Isi Informasi Pengguna</strong>
        <ul class="docs-list">
            <li><strong>Username</strong> — Nama login yang unik (tidak dapat diubah setelah dibuat).</li>
            <li><strong>Email</strong> — Alamat email aktif pengguna.</li>
            <li><strong>Nama Depan &amp; Belakang</strong> — Nama lengkap pengguna (opsional).</li>
            <li><strong>Password</strong> — Kata sandi akun (bisa dibuat otomatis atau diisi manual).</li>
        </ul>
    </li>
    <li><strong>Pilih Peran</strong><p>Pilih peran yang sesuai dari dropdown <em>Peran</em>.</p></li>
    <li><strong>Klik Tambah Pengguna Baru</strong><p>Klik tombol <strong>Tambah Pengguna Baru</strong> untuk menyimpan akun.</p></li>
</ol>

<div class="docs-warning">
    <span class="dashicons dashicons-warning"></span>
    <div>
        <strong>Perhatian:</strong> Berikan peran <em>Administrator</em> hanya kepada orang yang benar-benar terpercaya, karena mereka memiliki akses penuh ke seluruh sistem termasuk pengaturan kritis.
    </div>
</div>
