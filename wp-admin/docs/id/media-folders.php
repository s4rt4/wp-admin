<h1>Folder Media</h1>
<p class="docs-lead">Organisasi file media ke dalam folder virtual. Folder disimpan di database — tidak ada file yang dipindahkan di disk.</p>

<hr class="docs-divider">

<h2>Gambaran Umum</h2>
<p>Media Library kini memiliki sidebar folder di sisi kiri. Anda bisa membuat folder sebanyak yang dibutuhkan dan mengatur file dengan cara drag &amp; drop.</p>

<ul class="docs-list">
    <li>Folder bersifat <strong>virtual</strong> — file aslinya tetap berada di lokasi yang sama di disk.</li>
    <li>Satu file hanya bisa masuk ke satu folder dalam satu waktu.</li>
    <li>File yang tidak ditempatkan di folder mana pun akan muncul di <strong>All Media</strong>.</li>
</ul>

<hr class="docs-divider">

<h2>Membuat Folder</h2>
<ol class="docs-list">
    <li>Di Media Library, klik ikon <strong>+</strong> di bagian atas sidebar folder.</li>
    <li>Ketik nama folder lalu klik <strong>OK</strong>.</li>
    <li>Folder langsung muncul di tree sidebar.</li>
</ol>

<hr class="docs-divider">

<h2>Memasukkan File ke Folder</h2>
<ol class="docs-list">
    <li>Klik dan drag file media dari grid.</li>
    <li>Drop ke folder yang dituju di sidebar kiri — folder akan menyala biru saat Anda hover di atasnya.</li>
    <li>Halaman akan reload dan file sekarang tampil di dalam folder tersebut.</li>
</ol>
<p>Untuk mengeluarkan file dari folder (pindah ke root), drag file tersebut ke <strong>All Media</strong> di bagian atas sidebar.</p>

<hr class="docs-divider">

<h2>Filter Berdasarkan Folder</h2>
<p>Klik nama folder di sidebar untuk memfilter grid hanya menampilkan file di folder tersebut. Klik <strong>All Media</strong> untuk kembali ke tampilan seluruh library.</p>

<hr class="docs-divider">

<h2>Rename &amp; Hapus Folder</h2>
<ul class="docs-list">
    <li>Hover pada baris folder untuk memunculkan ikon <strong>edit</strong> (pensil) dan <strong>hapus</strong> (tempat sampah).</li>
    <li><strong>Rename:</strong> klik ikon pensil, ketik nama baru, klik OK.</li>
    <li><strong>Hapus:</strong> klik ikon tempat sampah dan konfirmasi. File di dalam folder yang dihapus otomatis dikembalikan ke root (All Media). Sub-folder naik satu level.</li>
</ul>

<div class="docs-warning">
    <strong>Perhatian:</strong> Menghapus folder <em>tidak</em> menghapus file — file hanya dibatalkan penugasannya.
</div>
