<h1>Pengaturan SEO</h1>
<p class="docs-lead">Optimalkan setiap post untuk mesin pencari menggunakan panel SEO bawaan — tulis meta title, meta description, dan focus keyword, lalu lihat tampilan post Anda di Google sebelum dipublikasikan.</p>

<hr class="docs-divider">

<h2>Membuka Panel SEO</h2>
<p>Kotak <strong>SEO Settings</strong> muncul di bawah editor konten utama pada setiap halaman edit post. Klik header-nya untuk memperluas atau menyembunyikannya.</p>

<hr class="docs-divider">

<h2>Preview Google Snippet</h2>
<p>Preview di bagian atas panel menampilkan simulasi live hasil pencarian Google Anda. Update secara real time saat Anda mengetik.</p>
<table class="docs-table">
    <thead><tr><th>Tab</th><th>Keterangan</th></tr></thead>
    <tbody>
        <tr><td><strong>🖥 Desktop</strong></td><td>Tampilan standar dengan favicon, nama situs, URL breadcrumb, judul, dan deskripsi.</td></tr>
        <tr><td><strong>📱 Mobile</strong></td><td>Tampilan ringkas seperti yang terlihat di perangkat mobile.</td></tr>
    </tbody>
</table>
<p>Judul akan menggunakan judul post jika field SEO Title kosong. Slug URL otomatis diperbarui saat Anda mengubah slug post.</p>

<hr class="docs-divider">

<h2>Field</h2>
<table class="docs-table">
    <thead><tr><th>Field</th><th>Panjang ideal</th><th>Keterangan</th></tr></thead>
    <tbody>
        <tr>
            <td><strong>SEO Title</strong></td>
            <td>30–60 karakter</td>
            <td>Judul yang ditampilkan di hasil pencarian. Kosongkan untuk menggunakan judul post. Bar warna melacak panjang (hijau = baik, oranye = terlalu panjang).</td>
        </tr>
        <tr>
            <td><strong>Meta Description</strong></td>
            <td>120–160 karakter</td>
            <td>Ringkasan singkat yang ditampilkan di bawah judul. Bar panjang membantu Anda tetap di rentang ideal.</td>
        </tr>
        <tr>
            <td><strong>Focus Keyword</strong></td>
            <td>1–4 kata</td>
            <td>Kata kunci utama yang ingin Anda targetkan. Digunakan untuk menjalankan checklist SEO Analysis.</td>
        </tr>
    </tbody>
</table>

<hr class="docs-divider">

<h2>SEO Analysis</h2>
<p>Panel <strong>SEO Analysis</strong> di bagian bawah menampilkan checklist dan skor (0–8) yang diperbarui saat Anda menulis.</p>
<table class="docs-table">
    <thead><tr><th>Pemeriksaan</th><th>Yang diverifikasi</th></tr></thead>
    <tbody>
        <tr><td>✅ Keyword di SEO title</td><td>Focus keyword muncul di field SEO Title.</td></tr>
        <tr><td>✅ Keyword di meta description</td><td>Focus keyword muncul di Meta Description.</td></tr>
        <tr><td>✅ Keyword di judul post</td><td>Focus keyword muncul di judul utama post.</td></tr>
        <tr><td>✅ Keyword di URL slug</td><td>Focus keyword (dengan tanda hubung) muncul di slug.</td></tr>
        <tr><td>✅ Keyword di konten</td><td>Focus keyword muncul minimal sekali di isi teks.</td></tr>
        <tr><td>✅ Panjang SEO title</td><td>SEO title antara 30–60 karakter.</td></tr>
        <tr><td>✅ Panjang meta description</td><td>Meta description antara 120–160 karakter.</td></tr>
        <tr><td>✅ Panjang konten</td><td>Isi post mengandung minimal 300 kata.</td></tr>
    </tbody>
</table>
<p>Bar skor berubah <strong style="color:#00a32a;">hijau</strong> (≥75%), <strong style="color:#dba617;">kuning</strong> (≥45%), atau <strong style="color:#d63638;">merah</strong> (&lt;45%) berdasarkan berapa banyak pemeriksaan yang lulus. Pemeriksaan keyword tersembunyi sampai Anda memasukkan Focus Keyword.</p>

<div class="docs-tip">
    <strong>Tips:</strong> Targetkan skor minimal 6/8 sebelum mempublikasikan. Perbaiki peringatan ⚠️ terlebih dahulu (masalah panjang) — itu adalah perbaikan yang mudah.
</div>
