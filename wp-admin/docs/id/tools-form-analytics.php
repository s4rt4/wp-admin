<h2>Form Analytics</h2>
<p>Form Analytics memberikan insight visual tentang tren pengiriman formulir dan tabel respons yang bisa dicari.</p>

<h3>Cara Mengakses</h3>
<p>Buka <strong>Tools → Form Analytics</strong> di sidebar admin.</p>

<h3>Fitur</h3>
<ul>
    <li><strong>Filter Form</strong> — Pilih form tertentu atau lihat semua form sekaligus.</li>
    <li><strong>Kartu Statistik</strong> — Total submission, jumlah hari ini, 7 hari terakhir, dan jumlah form aktif.</li>
    <li><strong>Chart Tren Submission</strong> — Bar chart menampilkan submission harian selama 30 hari terakhir (powered by Toast UI Chart).</li>
    <li><strong>Grid Respons</strong> — Tabel tui-grid interaktif berisi semua submission dengan nama form, preview data, dan timestamp. Bisa diurutkan dan dipaginasi.</li>
</ul>
