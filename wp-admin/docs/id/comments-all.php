<h2>Komentar</h2>
<p>Halaman Komentar memungkinkan Anda mengelola semua komentar di situs.</p>

<h3>Melihat Komentar</h3>
<p>Buka <strong>Comments</strong> di sidebar admin. Komentar diorganisir berdasarkan status:</p>
<ul>
    <li><strong>All</strong> — Semua komentar yang tidak di-trash.</li>
    <li><strong>Pending</strong> — Menunggu moderasi.</li>
    <li><strong>Approved</strong> — Dipublikasikan dan terlihat di situs.</li>
    <li><strong>Spam</strong> — Ditandai sebagai spam.</li>
    <li><strong>Trash</strong> — Komentar yang dihapus (bisa dipulihkan).</li>
</ul>

<h3>Aksi</h3>
<ul>
    <li><strong>Approve / Unapprove</strong> — Toggle visibilitas komentar.</li>
    <li><strong>Spam</strong> — Tandai sebagai spam.</li>
    <li><strong>Trash / Restore</strong> — Pindah ke atau dari trash.</li>
    <li><strong>Reply</strong> — Balas komentar langsung secara inline.</li>
    <li><strong>Bulk Actions</strong> — Pilih beberapa komentar dan terapkan aksi sekaligus.</li>
</ul>

<h3>Pengaturan</h3>
<p>Di bawah daftar komentar, Anda bisa konfigurasi:</p>
<ul>
    <li><strong>Auto-approve</strong> — Otomatis setujui komentar dari user yang sudah punya komentar disetujui.</li>
    <li><strong>Spam Blacklist</strong> — Kata kunci yang otomatis menandai komentar sebagai spam (satu per baris).</li>
</ul>
