<h1>Post Drafts</h1>
<p class="docs-lead">Drafts are unpublished posts. You can save content that is still being written as a draft and continue it at any time.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('draft-post.png'); ?>" alt="Post Drafts" onerror="this.style.display='none'">
    <p class="docs-caption">The list of posts saved as drafts.</p>
</div>

<hr class="docs-divider">

<h2>How to Manage Drafts</h2>
<ol class="docs-steps">
    <li>
        <strong>View All Drafts</strong>
        <p>Go to <strong>Posts &rarr; All Posts</strong>, then click the <strong>Draft</strong> tab at the top of the table.</p>
    </li>
    <li>
        <strong>Continue Writing a Draft</strong>
        <p>Click the title of the draft you want to continue to open the editor. Make changes and click <strong>Save Draft</strong> to save, or <strong>Publish</strong> when it's ready.</p>
    </li>
    <li>
        <strong>Schedule Publication</strong>
        <p>In the <em>Status &amp; Visibility</em> panel, click <em>Immediately</em> next to Publish, then set the desired publication date and time.</p>
    </li>
    <li>
        <strong>Delete a Draft</strong>
        <p>Hover over the draft title in the list and click <em>Delete</em> to permanently remove the draft.</p>
    </li>
</ol>

<hr class="docs-divider">

<h2>Draft Management Tips</h2>
<ul class="docs-list">
    <li>Create draft titles first even if the content isn't complete yet — this makes future content planning easier.</li>
    <li>Use the scheduling feature to ensure posts are published at optimal times (e.g., peak traffic hours).</li>
    <li>Add notes inside the draft about what still needs to be completed before publishing.</li>
</ul>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tip:</strong> Drafts are not visible to site visitors. You can use them to prepare content well in advance before the publication date.
    </div>
</div>
