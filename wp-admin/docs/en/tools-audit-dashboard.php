<h2>Audit Dashboard</h2>
<p>The Audit Dashboard provides a visual overview of all admin activity with charts and an interactive log grid.</p>

<h3>How to Access</h3>
<p>Navigate to <strong>Tools → Audit Dashboard</strong> in the admin sidebar. For the full filterable log, click "View Full Log" to go to the Audit Log page.</p>

<h3>Features</h3>
<ul>
    <li><strong>Stats Cards</strong> — Total events (30 days), today's events, and number of active users.</li>
    <li><strong>Activity Timeline</strong> — Area chart showing daily event counts over the last 30 days.</li>
    <li><strong>Top Actions</strong> — Horizontal bar chart of the most common action types (login, post_create, etc.).</li>
    <li><strong>Top Users</strong> — Horizontal bar chart of the most active users by event count.</li>
    <li><strong>Recent Activity Grid</strong> — Interactive tui-grid table with the latest 200 log entries. Color-coded action badges, sortable columns, and pagination.</li>
</ul>
