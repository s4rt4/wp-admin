<h2>Data Explorer</h2>
<p>The Data Explorer lets administrators browse any database table directly from the admin panel in a read-only, interactive grid.</p>

<h3>How to Access</h3>
<p>Navigate to <strong>Tools → Data Explorer</strong> in the admin sidebar. Requires <em>manage_options</em> capability.</p>

<h3>Features</h3>
<ul>
    <li><strong>Table Selector</strong> — Dropdown listing all database tables. Select one to load its data.</li>
    <li><strong>Auto-detect Columns</strong> — Column headers and widths are automatically determined from the table schema.</li>
    <li><strong>Sorting</strong> — Click any column header to sort ascending/descending.</li>
    <li><strong>Pagination</strong> — 50 rows per page with client-side pagination.</li>
    <li><strong>CSV Export</strong> — Download the table data as a CSV file.</li>
    <li><strong>Column Info</strong> — Displays column names and data types below the toolbar.</li>
</ul>

<h3>Limitations</h3>
<ul>
    <li>Read-only — no editing or deleting from this page.</li>
    <li>Maximum 500 rows displayed per table.</li>
    <li>Large TEXT/BLOB columns may be truncated in the grid view.</li>
</ul>
