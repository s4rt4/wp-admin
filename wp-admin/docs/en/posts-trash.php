<h2>Trash / Recycle Bin</h2>

<p>When you delete a post or page, it is not permanently removed. Instead, it moves to <strong>Trash</strong> — a safe holding area where items can be restored or permanently deleted.</p>

<h3>How it works</h3>
<ul>
    <li><strong>Trash:</strong> Click "Trash" on any post or page row action to soft-delete it. The item's status changes to <code>trash</code> and it disappears from the main list.</li>
    <li><strong>Trash Tab:</strong> A red "Trash" filter tab appears in the Posts and Pages list when there are trashed items. Click it to view all trashed content.</li>
    <li><strong>Restore:</strong> In the Trash view, click "Restore" to move the item back to <strong>Draft</strong> status.</li>
    <li><strong>Delete Permanently:</strong> Click "Delete Permanently" to irreversibly remove the item and all associated data (categories, tags, custom fields).</li>
    <li><strong>Empty Trash:</strong> Click the "Empty Trash" button at the top to permanently delete all trashed items at once.</li>
</ul>

<h3>Notes</h3>
<ul>
    <li>Trashed posts are excluded from the "All" count and will not appear on the frontend.</li>
    <li>The Trash tab only appears when there is at least one trashed item.</li>
    <li>Both Posts and Pages support the Trash feature.</li>
</ul>
