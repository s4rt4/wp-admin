<h2>Media Editor</h2>
<p>Edit images directly from the Media Library without downloading and re-uploading. The built-in editor supports crop, resize, rotate, and flip.</p>

<h3>How to Open</h3>
<ol>
    <li>Go to <strong>Media</strong> and click on any image.</li>
    <li>In the detail panel, click the <strong>Edit Image</strong> button.</li>
    <li>The image editor modal opens with a dark canvas workspace.</li>
</ol>

<h3>Tools</h3>
<ul>
    <li><strong>Rotate Left / Right:</strong> Rotate the image 90 degrees.</li>
    <li><strong>Flip Horizontal / Vertical:</strong> Mirror the image along the horizontal or vertical axis.</li>
    <li><strong>Resize:</strong> Enter new width (W) or height (H). The aspect ratio lock (padlock icon) keeps proportions by default — click to unlock for free resizing.</li>
    <li><strong>Crop:</strong> Click the Crop button, then drag a selection rectangle on the canvas. Click Crop again to apply — the image is trimmed to your selection.</li>
    <li><strong>Reset:</strong> Revert all changes back to the original image.</li>
</ul>

<h3>Saving</h3>
<p>Click <strong>Save</strong> to overwrite the original file with your edits. The file size in the media database is updated automatically. This action cannot be undone — consider downloading a backup first if needed.</p>
