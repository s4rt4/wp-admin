<h1>Published Posts</h1>
<p class="docs-lead">The <strong>Published Posts</strong> page displays all articles that are live and accessible to site visitors.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('published-post.png'); ?>" alt="Published Posts" onerror="this.style.display='none'">
    <p class="docs-caption">The list of published posts.</p>
</div>

<hr class="docs-divider">

<h2>How to Manage Published Posts</h2>
<ol class="docs-steps">
    <li>
        <strong>Filter Published Posts</strong>
        <p>Go to <strong>Posts &rarr; All Posts</strong>, then click the <strong>Published</strong> tab to view only live posts.</p>
    </li>
    <li>
        <strong>Edit a Live Post</strong>
        <p>Click the post title to open the editor and make changes. Click <strong>Update</strong> to save. The post remains live during editing.</p>
    </li>
    <li>
        <strong>Revert to Draft</strong>
        <p>Open the post editor, change the status from <em>Published</em> to <em>Draft</em>, then click <strong>Update</strong>. The post will be hidden from the public.</p>
    </li>
    <li>
        <strong>Delete a Post</strong>
        <p>Hover over the post title in the list and click <em>Delete</em>. This action is permanent.</p>
    </li>
</ol>

<div class="docs-warning">
    <span class="dashicons dashicons-warning"></span>
    <div>
        <strong>Warning:</strong> Changes made to a published post will be immediately visible to site visitors after saving. Make sure content has been reviewed before updating.
    </div>
</div>

<hr class="docs-divider">

<h2>Tips for Managing Published Content</h2>
<ul class="docs-list">
    <li>Regularly review older posts to ensure the information is still relevant and accurate.</li>
    <li>Update the post date if you make major content updates so it appears fresher to search engines.</li>
    <li>Use the post duplication feature if you want to create a similar post without starting from scratch.</li>
</ul>
