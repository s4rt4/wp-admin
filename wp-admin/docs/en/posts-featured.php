<h1>Featured Posts</h1>
<p class="docs-lead">The <strong>Featured Posts</strong> feature allows you to mark specific posts to appear in more prominent positions on your site's pages, such as sliders, banners, or hero sections on the homepage.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('featured-posts.png'); ?>" alt="Featured Posts Page" onerror="this.style.display='none'">
    <p class="docs-caption">The list of posts marked as featured.</p>
</div>

<hr class="docs-divider">

<h2>How to Manage Featured Posts</h2>
<ol class="docs-steps">
    <li>
        <strong>Filter Featured Posts</strong>
        <p>Go to <strong>Posts &rarr; All Posts</strong>, then click the <strong>Featured</strong> tab at the top of the table to view only marked posts.</p>
    </li>
    <li>
        <strong>Mark a Post as Featured</strong>
        <p>Open the editor for the post you want to feature. In the right-hand panel, enable the <em>Mark as Featured</em> option (toggle or checkbox).</p>
    </li>
    <li>
        <strong>Remove Featured Status</strong>
        <p>Reopen the post editor and disable the <em>Mark as Featured</em> option that was previously enabled.</p>
    </li>
</ol>

<hr class="docs-divider">

<h2>How Featured Posts Work</h2>
<p>Posts marked as featured will:</p>
<ul class="docs-list">
    <li>Appear in the <strong>Featured Posts</strong> section or slider on the homepage (depending on theme configuration).</li>
    <li>Be displayed with a special <em>"Featured"</em> label in the admin post list.</li>
    <li>Be filterable and manageable from the Featured tab on the All Posts page.</li>
</ul>

<div class="docs-tip">
    <span class="dashicons dashicons-lightbulb"></span>
    <div>
        <strong>Tip:</strong> Choose featured posts that have high-quality images and compelling titles, as these posts are usually displayed most prominently on the site's homepage.
    </div>
</div>
