<h1>SEO Settings</h1>
<p class="docs-lead">Optimise every post for search engines using the built-in SEO panel — write meta titles, meta descriptions, and a focus keyword, then see exactly how your post will appear in Google results before you publish.</p>

<hr class="docs-divider">

<h2>Opening the SEO Panel</h2>
<p>The <strong>SEO Settings</strong> box appears below the main content editor on every post edit page. Click the header to collapse or expand it.</p>

<hr class="docs-divider">

<h2>Google Snippet Preview</h2>
<p>The preview at the top of the panel shows a live simulation of your Google search result. It updates in real time as you type.</p>
<table class="docs-table">
    <thead><tr><th>Tab</th><th>Description</th></tr></thead>
    <tbody>
        <tr><td><strong>🖥 Desktop</strong></td><td>Standard result with favicon, site name, breadcrumb URL, title, and description.</td></tr>
        <tr><td><strong>📱 Mobile</strong></td><td>Compact version as seen on mobile devices.</td></tr>
    </tbody>
</table>
<p>The title falls back to the post title when the SEO Title field is empty. The URL slug updates automatically when you change the post slug.</p>

<hr class="docs-divider">

<h2>Fields</h2>
<table class="docs-table">
    <thead><tr><th>Field</th><th>Recommended length</th><th>Notes</th></tr></thead>
    <tbody>
        <tr>
            <td><strong>SEO Title</strong></td>
            <td>30–60 characters</td>
            <td>The title shown in search results. Leave blank to use the post title. A colour-coded bar tracks length (green = good, orange = too long).</td>
        </tr>
        <tr>
            <td><strong>Meta Description</strong></td>
            <td>120–160 characters</td>
            <td>The short summary shown under the title. A length bar helps you stay in the ideal range.</td>
        </tr>
        <tr>
            <td><strong>Focus Keyword</strong></td>
            <td>1–4 words</td>
            <td>The primary keyword you want the post to rank for. Used to power the SEO Analysis checklist.</td>
        </tr>
    </tbody>
</table>

<hr class="docs-divider">

<h2>SEO Analysis</h2>
<p>The <strong>SEO Analysis</strong> panel at the bottom shows a checklist and score (0–8) that updates as you write.</p>
<table class="docs-table">
    <thead><tr><th>Check</th><th>What it verifies</th></tr></thead>
    <tbody>
        <tr><td>✅ Keyword in SEO title</td><td>Focus keyword appears in the SEO Title field.</td></tr>
        <tr><td>✅ Keyword in meta description</td><td>Focus keyword appears in the Meta Description.</td></tr>
        <tr><td>✅ Keyword in post title</td><td>Focus keyword appears in the post's main title.</td></tr>
        <tr><td>✅ Keyword in URL slug</td><td>Focus keyword (hyphenated) appears in the slug.</td></tr>
        <tr><td>✅ Keyword in content</td><td>Focus keyword appears at least once in the body text.</td></tr>
        <tr><td>✅ SEO title length</td><td>SEO title is between 30 and 60 characters.</td></tr>
        <tr><td>✅ Meta description length</td><td>Meta description is between 120 and 160 characters.</td></tr>
        <tr><td>✅ Content length</td><td>Post body contains at least 300 words.</td></tr>
    </tbody>
</table>
<p>The score bar turns <strong style="color:#00a32a;">green</strong> (≥75 %), <strong style="color:#dba617;">yellow</strong> (≥45 %), or <strong style="color:#d63638;">red</strong> (&lt;45 %) based on how many checks pass. Keyword checks are hidden until you enter a Focus Keyword.</p>

<div class="docs-tip">
    <strong>Tip:</strong> Aim for a score of at least 6/8 before publishing. Fix ⚠️ warnings first (length issues) — they're easy wins.
</div>
