<h1>Appearance Customization</h1>
<p class="docs-lead">The <strong>Appearance &rarr; Customize</strong> menu allows you to change the visual look of your site — colors, fonts, header, footer, and other design elements — directly through the admin panel.</p>

<div class="docs-screenshot">
    <img src="<?php echo get_docs_asset_url('customize.png'); ?>" alt="Appearance Customization Page" onerror="this.style.display='none'">
    <p class="docs-caption">The site appearance customization panel.</p>
</div>

<hr class="docs-divider">

<h2>How to Customize Appearance</h2>
<ol class="docs-steps">
    <li>
        <strong>Open the Customization Panel</strong>
        <p>Click <strong>Appearance &rarr; Customize</strong> in the admin sidebar.</p>
    </li>
    <li>
        <strong>Select a Section to Change</strong>
        <p>In the left panel, you'll see various customization options. Click one to open its settings:</p>
        <ul class="docs-list">
            <li><strong>Site Identity</strong> — Change the site name, tagline, and favicon.</li>
            <li><strong>Colors</strong> — Adjust the site's primary color scheme.</li>
            <li><strong>Header</strong> — Customize the top section of the page.</li>
            <li><strong>Footer</strong> — Set the content and appearance of the page bottom.</li>
            <li><strong>Typography</strong> — Choose fonts and text sizes.</li>
        </ul>
    </li>
    <li>
        <strong>View Live Preview</strong>
        <p>Every change you make will immediately be visible in the preview area to the right of the panel.</p>
    </li>
    <li>
        <strong>Save Changes</strong>
        <p>Click the <strong>Publish</strong> button to apply all changes to the live site.</p>
    </li>
</ol>

