<h2>Comments</h2>
<p>The Comments page lets you manage all comments across your site.</p>

<h3>Viewing Comments</h3>
<p>Navigate to <strong>Comments</strong> in the admin sidebar. Comments are organized by status:</p>
<ul>
    <li><strong>All</strong> — All non-trashed comments.</li>
    <li><strong>Pending</strong> — Awaiting moderation.</li>
    <li><strong>Approved</strong> — Published and visible on the site.</li>
    <li><strong>Spam</strong> — Marked as spam.</li>
    <li><strong>Trash</strong> — Deleted comments (can be restored).</li>
</ul>

<h3>Actions</h3>
<ul>
    <li><strong>Approve / Unapprove</strong> — Toggle comment visibility.</li>
    <li><strong>Spam</strong> — Mark as spam.</li>
    <li><strong>Trash / Restore</strong> — Move to or from trash.</li>
    <li><strong>Reply</strong> — Post an admin reply inline.</li>
    <li><strong>Bulk Actions</strong> — Select multiple comments and apply an action at once.</li>
</ul>

<h3>Settings</h3>
<p>Below the comments list, you can configure:</p>
<ul>
    <li><strong>Auto-approve</strong> — Automatically approve comments from users with a previously approved comment.</li>
    <li><strong>Spam Blacklist</strong> — Keywords that automatically mark comments as spam (one per line).</li>
</ul>
