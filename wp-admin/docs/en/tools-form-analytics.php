<h2>Form Analytics</h2>
<p>Form Analytics provides visual insights into form submission trends and a searchable table of all responses.</p>

<h3>How to Access</h3>
<p>Navigate to <strong>Tools → Form Analytics</strong> in the admin sidebar.</p>

<h3>Features</h3>
<ul>
    <li><strong>Form Filter</strong> — Select a specific form or view all forms combined.</li>
    <li><strong>Stats Cards</strong> — Total submissions, today's count, last 7 days, and number of active forms.</li>
    <li><strong>Submission Trends Chart</strong> — Bar chart showing daily submissions over the last 30 days (powered by Toast UI Chart).</li>
    <li><strong>Responses Grid</strong> — Interactive tui-grid table listing all submissions with form name, data preview, and timestamp. Sortable and paginated.</li>
</ul>
