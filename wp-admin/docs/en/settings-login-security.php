<h2>Login Security</h2>
<p>Monitor and manage login activity across your CMS.</p>

<h3>Dashboard</h3>
<ul>
    <li><strong>Stats Cards</strong> — Successful logins, failed attempts, unique IPs, active sessions (last 30 days).</li>
    <li><strong>Failed Attempts Chart</strong> — Timeline of failed login attempts over the last 14 days.</li>
    <li><strong>Top Failed IPs</strong> — IP addresses with the most failed login attempts.</li>
    <li><strong>Active Sessions</strong> — Users currently online (active in the last 15 minutes). Force-logout button for other users.</li>
    <li><strong>Recent Attempts</strong> — Log of the latest 20 login attempts with success/fail status, IP, and timestamp.</li>
</ul>
