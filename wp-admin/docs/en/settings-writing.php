<h2>Writing Settings Options</h2>
<table class="docs-table">
    <thead>
        <tr><th>Setting</th><th>Description</th></tr>
    </thead>
    <tbody>
        <tr><td><strong>Default Post Category</strong></td><td>The category automatically selected when creating a new post if no category is manually selected.</td></tr>
        <tr><td><strong>Default Post Format</strong></td><td>The default post display format (Standard, Gallery, Video, Audio, etc.).</td></tr>
        <tr><td><strong>Post via Email</strong></td><td>Configuration for publishing posts via email (if supported).</td></tr>
        <tr><td><strong>Update Services</strong></td><td>List of notification services to be pinged when a new post is published.</td></tr>
    </tbody>
</table>

