<h2>Revision Diff Viewer</h2>

<p>The Revision Diff Viewer lets you compare two versions of a post side-by-side, highlighting what was added and removed between revisions.</p>

<h3>How to Use</h3>
<ol>
    <li>Open a post for editing (<strong>Posts &rarr; Edit</strong>).</li>
    <li>In the sidebar, expand the <strong>Revisions</strong> metabox.</li>
    <li>Each revision entry has a <strong>Compare</strong> button (<i class="fa-solid fa-code-compare"></i>) — click it to compare that revision with the one below it (the previous version).</li>
    <li>A modal opens showing both versions side-by-side:
        <ul>
            <li><span style="color:#991b1b;background:#fecaca;padding:1px 4px;">Red lines</span> = text that was removed (older version).</li>
            <li><span style="color:#166534;background:#bbf7d0;padding:1px 4px;">Green lines</span> = text that was added (newer version).</li>
            <li>Unchanged lines appear normally in both columns.</li>
        </ul>
    </li>
</ol>

<h3>Restoring a Revision</h3>
<p>Click <strong>Restore</strong> next to any revision to replace the current editor content with that revision's content. Remember to save the post after restoring.</p>

<h3>Notes</h3>
<ul>
    <li>A new revision is automatically saved every time you update a post.</li>
    <li>Only the last 20 revisions per post are kept.</li>
    <li>The diff viewer compares plain text content (HTML tags are stripped for readability).</li>
</ul>
