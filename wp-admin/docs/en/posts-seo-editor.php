<h2>Bulk SEO Editor</h2>
<p>The Bulk SEO Editor lets you edit SEO metadata for all posts in one spreadsheet-like view, without opening each post individually.</p>

<h3>How to Access</h3>
<p>Navigate to <strong>Posts → Bulk SEO Editor</strong> in the admin sidebar.</p>

<h3>Editable Fields</h3>
<ul>
    <li><strong>SEO Title</strong> — The title shown in search engine results. Optimal length: 30–60 characters. Character count shown in parentheses with colour indicator.</li>
    <li><strong>Meta Description</strong> — The snippet shown below the title in search results. Optimal length: 120–160 characters.</li>
    <li><strong>Slug</strong> — The URL-friendly identifier for the post.</li>
    <li><strong>Focus Keyword</strong> — The primary keyword you want the post to rank for.</li>
</ul>

<h3>How to Edit</h3>
<ol>
    <li>Click on any editable cell (SEO Title, Meta Description, Slug, or Focus Keyword).</li>
    <li>Type your changes.</li>
    <li>Press <kbd>Enter</kbd> or click outside the cell to save.</li>
    <li>A green "Saved" indicator appears briefly to confirm.</li>
</ol>

<h3>Colour Indicators</h3>
<ul>
    <li><span style="color:#065f46;font-weight:600;">Green</span> — Length is within the optimal range.</li>
    <li><span style="color:#856404;font-weight:600;">Yellow</span> — Has content but outside the optimal range.</li>
    <li><span style="color:#d63638;font-weight:600;">Red</span> — Empty or needs attention.</li>
</ul>

<h3>Search & Sort</h3>
<p>Use the search bar to filter posts by title or slug. Click any column header to sort the grid.</p>
