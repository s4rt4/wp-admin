<h2>Internal Messaging</h2>
<p>Send and receive messages between admin users directly within the CMS.</p>

<h3>Features</h3>
<ul>
    <li><strong>Inbox / Sent</strong> — Toggle between received and sent messages.</li>
    <li><strong>Compose</strong> — Click the compose section to expand the form. Select a user, add a subject, and write your message.</li>
    <li><strong>Reply Thread</strong> — Click a message to view it with all replies in a thread. Reply directly from the view page.</li>
    <li><strong>Unread Badges</strong> — Unread count shown on the Inbox tab.</li>
    <li><strong>Notifications</strong> — Recipients automatically receive an in-app notification when they get a new message.</li>
</ul>
